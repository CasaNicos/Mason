"""
mason_news.py — Phase 2: Mason's trader-grade news flow engine.

Turns raw headlines into a structured, ranked flow that reads like a trading
desk's news app: each item is tagged with the ticker(s) it touches, a 🔴🟡🟢
impact dot scored against Nico's book, and a one-line *implication* ("Oil +3%
OPEC → XLE short strike tested") generated by the local qwen model.

Sources: FMP stock_news (holdings + watchlist tickers, and general market) —
ticker-tagged, which is what gives the trader-app feel. The Flask /api/news
route merges these with the existing RSS macro headlines.

Design notes:
  - TTL cache (90s) protects the FMP daily quota.
  - Implications are generated in ONE batched call to the mason_llm gateway
    (intent="chore" → local qwen3.5:4b) for the top items, then cached by
    item-id so refreshes are instant. No cloud key, no per-token cost.
  - Everything degrades gracefully: no FMP key / no network → empty flow, and
    if the local gateway is down (mason_llm.LocalModelError) the items come
    back without implications. Never raises.

Public API:
    fetch_flow(limit=25, with_implications=True) -> list[dict]
    holdings_set() / watchlist_set() -> set[str]
"""

import json
import re
import time
import hashlib
from datetime import datetime, timezone, timedelta
from pathlib import Path

import requests

import mason_llm

BASE        = Path(__file__).parent
CONFIG      = BASE / "mason.config.json"
IMPL_CACHE  = BASE / "mason_news_cache.json"

# ── flow cache (quota guard) ───────────────────────────────────────────────────
_FLOW_TTL   = 90  # seconds
_flow_cache = {"ts": 0, "data": None}

# ── impact heuristics ──────────────────────────────────────────────────────────
_RED = re.compile(r"\b(cut|cuts|miss|misses|missed|plunge|plunges|slump|slumps|"
                  r"downgrade[sd]?|halt|halts|halted|lawsuit|recall|bankrupt|"
                  r"probe|investigat|fraud|default|warning|warns|slash|slashes|"
                  r"tariff|sanction|war|strike[sd]?|layoff|guidance cut|sinks|"
                  r"tumble|tumbles|crash|crashes|selloff|sell-off|fears?)\b", re.I)
_GREEN = re.compile(r"\b(beat|beats|tops|surge|surges|soar|soars|jump|jumps|"
                    r"rally|rallies|upgrade[sd]?|record|approval|approve[sd]?|"
                    r"buyback|raises guidance|raise[sd]? guidance|wins?|"
                    r"signs?|breakthrough|outperform|spikes?|climbs?|"
                    r"all-time high)\b", re.I)


# ── config / universe ──────────────────────────────────────────────────────────

def _cfg():
    try:
        return json.loads(CONFIG.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _fmp_key():
    import mason_secrets as _S    # B1b: env > secrets file > config (byte-exact legacy)
    return _S.get("FMP_API_KEY", "", cfg=_cfg())


def holdings_set():
    s = set()
    try:
        import mason_options
        s |= {p["ticker"].upper() for p in mason_options.get_open_plays()}
    except Exception:
        pass
    try:
        import mason_trades
        s |= {t["ticker"].upper() for t in mason_trades.get_open_trades()}
    except Exception:
        pass
    return s


def personal_held_set():
    """Tickers Nico holds in his own real accounts: the open personal_positions rows (the Robinhood mirror and any
    hand-entered account), read from the database through mason_personal (no broker call). Never a row of an account
    Mason must leave out (mason_robinhood.excluded_accounts(): the family account), never a blank account label,
    never the CASH line. Empty on any failure (fails closed). Review fix 2026-11-19 (old-snapshot sweep): used only as
    listing knowledge (mason_factcheck.load_ticker_master), never as "held" or as a trade candidate."""
    try:
        import mason_personal
        import mason_robinhood as RH
        excl = set(RH.excluded_accounts())
        out = set()
        for p in mason_personal.get_open_positions():
            lab = RH.norm_account_label(p.get("account_label"))
            tk = str(p.get("ticker") or "").strip().upper()
            if not lab or lab in excl or lab == "__healthcheck__" or not tk or tk == "CASH":
                continue
            out.add(tk)
        return out
    except Exception:
        return set()


def watchlist_set():
    seed = {"SPY", "QQQ", "VIX", "TSM", "NVDA", "IONQ", "RKLB",
            "XLE", "XLV", "OXY", "USO", "LMT", "MU"}
    # live watchlist items (mason_watchlist, 2026-09-30) join news tagging; the seed
    # above stays for news only (design A4). No-op while watchlist.enabled is false.
    live = set()
    try:
        import mason_watchlist
        if mason_watchlist.enabled():
            live = {str(i["ticker"]).upper() for i in mason_watchlist.list_items(status="active")
                    if i.get("ticker")}
    except Exception:
        pass
    return seed | holdings_set() | live


# ── impact + tagging ───────────────────────────────────────────────────────────

def _impact(headline, touches_holding):
    if _RED.search(headline):
        return "red"
    if _GREEN.search(headline):
        return "green" if touches_holding else "yellow"
    return "yellow" if touches_holding else "green"


def _tag_tickers(headline, symbol, universe):
    tags = set()
    if symbol:
        tags.add(symbol.upper())
    # scan headline for any universe ticker as a standalone token
    for t in universe:
        if re.search(rf"\b{re.escape(t)}\b", headline):
            tags.add(t)
    return sorted(tags)


def _is_overnight(dt_utc):
    """True if published on a weekend or outside ~regular US market hours."""
    try:
        et = dt_utc.astimezone(timezone(timedelta(hours=-4)))  # ET (DST-approx)
        if et.weekday() >= 5:
            return True
        mins = et.hour * 60 + et.minute
        return mins < 570 or mins >= 960   # before 9:30 or after 16:00
    except Exception:
        return False


def _parse_dt(s):
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d"):
        try:
            return datetime.strptime(s[:19], fmt).replace(tzinfo=timezone.utc)
        except Exception:
            continue
    return datetime.now(timezone.utc)


def _iid(headline):
    return hashlib.sha1(headline[:80].encode("utf-8", "ignore")).hexdigest()[:10]


# ── FMP fetch ──────────────────────────────────────────────────────────────────

def _fmp_news(tickers=None, limit=30):
    key = _fmp_key()
    if not key:
        return []
    try:
        if tickers:
            tk = ",".join(sorted(tickers)[:20])
            url = (f"https://financialmodelingprep.com/api/v3/stock_news"
                   f"?tickers={tk}&limit={limit}&apikey={key}")
        else:
            url = (f"https://financialmodelingprep.com/api/v3/stock_news"
                   f"?limit={limit}&apikey={key}")
        r = requests.get(url, timeout=10)
        return r.json() if r.ok else []
    except Exception:
        return []


# ── implications (batched local-qwen call via mason_llm gateway) ───────────────

def _load_impl_cache():
    try:
        return json.loads(IMPL_CACHE.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _save_impl_cache(d):
    try:
        # keep it from growing unbounded
        if len(d) > 400:
            d = dict(list(d.items())[-300:])
        IMPL_CACHE.write_text(json.dumps(d), encoding="utf-8")
    except Exception:
        pass


def _generate_implications(items, holdings, cap=8):
    """Fill item['implication'] for the top `cap` book-relevant items, cached."""
    cache = _load_impl_cache()
    # assign cached implications first
    need = []
    for it in items:
        c = cache.get(it["id"])
        if c is not None:
            it["implication"] = c or None
        elif (it["category"] in ("holding", "watchlist")) and len(need) < cap:
            need.append(it)
    if not need:
        return items

    try:
        book = ", ".join(sorted(holdings)) or "(none)"
        listing = "\n".join(f'{it["id"]}: [{",".join(it["tickers"]) or "—"}] {it["headline"]}'
                            for it in need)
        prompt = (
            f"Nico's book / watchlist: {book}.\n\n"
            f"For each headline below, write ONE terse line (max ~14 words) on the "
            f"concrete implication for HIS positions — what it pressures, helps, or "
            f"signals. If it's truly irrelevant to him, return an empty string.\n\n"
            f"{listing}\n\n"
            f'Respond JSON only: {{"<id>": "<implication or empty>", ...}}'
        )
        raw = mason_llm.complete("", prompt, intent="chore", num_predict=500).strip()
        if raw.startswith("```"):
            raw = raw.split("\n", 1)[1].rsplit("```", 1)[0]
        out = json.loads(raw)
        for it in need:
            impl = (out.get(it["id"]) or "").strip()
            it["implication"] = impl or None
            cache[it["id"]] = impl
        _save_impl_cache(cache)
    except mason_llm.LocalModelError:
        pass
    except Exception:
        pass
    return items


# ── assembly ───────────────────────────────────────────────────────────────────

def _build(limit, with_implications):
    holds = holdings_set()
    watch = watchlist_set()

    raw = _fmp_news(tickers=watch, limit=max(limit, 30))
    raw += _fmp_news(tickers=None, limit=20)   # general market / macro

    seen, items = set(), []
    for a in raw:
        headline = (a.get("title") or "").strip()
        if not headline:
            continue
        k = headline[:60].lower()
        if k in seen:
            continue
        seen.add(k)

        symbol = (a.get("symbol") or "").upper()
        tickers = _tag_tickers(headline, symbol, watch)
        touches_hold = any(t in holds for t in tickers)
        if any(t in holds for t in tickers):
            category = "holding"
        elif tickers:
            category = "watchlist"
        else:
            category = "macro"
        dt = _parse_dt(a.get("publishedDate", ""))
        items.append({
            "id":          _iid(headline),
            "ts":          dt.timestamp(),
            "time_str":    dt.strftime("%-I:%M%p").lower(),
            "tickers":     tickers,
            "headline":    headline,
            "source":      a.get("site", ""),
            "url":         a.get("url", ""),
            "category":    category,
            "impact":      _impact(headline, touches_hold),
            "implication": None,
            "overnight":   _is_overnight(dt),
        })

    # rank: overnight first, then impact (red>yellow>green), then recency
    rank = {"red": 0, "yellow": 1, "green": 2}
    items.sort(key=lambda i: (not i["overnight"], rank.get(i["impact"], 3), -i["ts"]))
    items = items[:limit]

    if with_implications:
        items = _generate_implications(items, holds)
    return items


def fetch_flow(limit=25, with_implications=True):
    now = time.time()
    if _flow_cache["data"] is not None and (now - _flow_cache["ts"]) < _FLOW_TTL:
        return _flow_cache["data"]
    try:
        data = _build(limit, with_implications)
    except Exception:
        data = []
    _flow_cache["ts"] = now
    _flow_cache["data"] = data
    return data


if __name__ == "__main__":
    import sys
    impl = "--no-impl" not in sys.argv
    flow = fetch_flow(with_implications=impl)
    print(f"{len(flow)} items\n")
    for it in flow[:15]:
        dot = {"red": "🔴", "yellow": "🟡", "green": "🟢"}[it["impact"]]
        tags = ("[" + ",".join(it["tickers"]) + "] ") if it["tickers"] else ""
        on = "🌙" if it["overnight"] else "  "
        print(f"{on}{dot} {it['time_str']:>7} {tags}{it['headline'][:80]}")
        if it["implication"]:
            print(f"          ↳ {it['implication']}")
